"""Extract native gettext messages and build/check deterministic catalogs (no packages)."""

import argparse
import ast
import gettext
import io
import json
from pathlib import Path
import re
import struct
import subprocess

ROOT = Path(__file__).resolve().parent.parent
LANGUAGES = ROOT / "languages"


def extract():
    return json.loads(
        subprocess.check_output(["php", str(ROOT / "tools/extract-messages.php")], text=True)
    )


def read_po(path):
    entries = []
    entry = {}
    field = None
    for line in path.read_text().splitlines() + [""]:
        if not line.strip():
            if entry:
                entries.append(entry)
            entry, field = {}, None
            continue
        if line.startswith("#, fuzzy"):
            raise ValueError("Fuzzy translations must be reviewed")
        if line.startswith("#"):
            continue
        match = re.fullmatch(r'(msgid_plural|msgid|msgstr(?:\[\d+\])?)\s+(".*")', line)
        if match:
            field = match[1]
            entry[field] = ast.literal_eval(match[2])
        elif line.startswith('"') and field:
            entry[field] += ast.literal_eval(line)
        else:
            raise ValueError("Unsupported PO syntax: " + line)
    ids = [entry["msgid"] for entry in entries]
    if len(set(ids)) != len(ids):
        raise ValueError("Duplicate message IDs")
    return {entry["msgid"]: entry for entry in entries}


def header(language=""):
    return (
        "Project-Id-Version: PageNest Companion\n"
        "PO-Revision-Date: 2026-10-13 00:00+0000\n"
        "Last-Translator: PageNest Companion Contributors\n"
        "Language-Team: PageNest Companion Contributors\n"
        "MIME-Version: 1.0\n"
        "Content-Type: text/plain; charset=UTF-8\n"
        "Content-Transfer-Encoding: 8bit\n"
        "X-Domain: pagenest-companion\n"
        + ("Language: " + language + "\nPlural-Forms: nplurals=1; plural=0;\n" if language else "")
    )


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def pot(messages):
    parts = [
        '# PageNest Companion translation template. Generated by npm run i18n.\nmsgid ""\nmsgstr '
        + quote(header())
    ]
    for item in messages:
        block = ["#: " + " ".join(item["references"])]
        if placeholders(item["id"]):
            block.append("#, php-format")
        block.append("msgid " + quote(item["id"]))
        if item["plural"]:
            block += ["msgid_plural " + quote(item["plural"]), 'msgstr[0] ""', 'msgstr[1] ""']
        else:
            block.append('msgstr ""')
        parts.append("\n".join(block))
    return ("\n\n".join(parts) + "\n").encode()


def placeholders(value):
    # Match WordPress/PHP sprintf placeholders; escaped %% is not a parameter.
    return sorted(re.findall(r"%(?:[1-9][0-9]*\$)?[dsf]", value.replace("%%", "")))


def catalog(entries):
    pairs = []
    for key, item in entries.items():
        if "msgid_plural" in item:
            key += "\0" + item["msgid_plural"]
            value = item["msgstr[0]"]  # Bundled Simplified Chinese has one plural form.
        else:
            value = item["msgstr"]
        pairs.append((key.encode(), value.encode()))
    pairs.sort()
    count = len(pairs)
    offset = 28 + 16 * count
    originals = b"".join(key + b"\0" for key, _ in pairs)
    translated = b"".join(value + b"\0" for _, value in pairs)
    original_table = []
    translation_table = []
    cursor, translation_cursor = offset, offset + len(originals)
    for key, value in pairs:
        original_table.extend([len(key), cursor])
        translation_table.extend([len(value), translation_cursor])
        cursor += len(key) + 1
        translation_cursor += len(value) + 1
    values = (
        [0x950412DE, 0, count, 28, 28 + 8 * count, 0, offset] + original_table + translation_table
    )
    return struct.pack("<" + "I" * len(values), *values) + originals + translated


def validate(messages, entries):
    expected = {item["id"] for item in messages}
    assert expected == set(entries) - {""}, "PO entries differ from current extracted messages"
    for item in messages:
        entry = entries[item["id"]]
        assert entry.get("msgid_plural") == item["plural"], "Plural mismatch: " + item["id"]
        translated = entry.get("msgstr[0]" if item["plural"] else "msgstr", "")
        assert translated, "Missing translation: " + item["id"]
        assert placeholders(translated) == placeholders(item["id"]), (
            "Placeholder mismatch: " + item["id"]
        )
        if item["plural"]:
            assert placeholders(item["plural"]) == placeholders(item["id"])
    compiled = catalog(entries)
    reader = gettext.GNUTranslations(io.BytesIO(compiled))
    for item in messages:
        actual = (
            reader.ngettext(item["id"], item["plural"], 2)
            if item["plural"]
            else reader.gettext(item["id"])
        )
        expected_translation = entries[item["id"]]["msgstr[0]" if item["plural"] else "msgstr"]
        assert actual == expected_translation, "MO lookup mismatch"
    return compiled


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    messages = extract()
    entries = read_po(LANGUAGES / "zh_CN.po")
    files = {
        "pagenest-companion.pot": pot(messages),
        "pagenest-companion-zh_CN.mo": validate(messages, entries),
    }
    for name, data in files.items():
        path = LANGUAGES / name
        if args.check:
            assert path.read_bytes() == data, "Stale catalog: " + name + "; run npm run i18n"
        else:
            path.write_bytes(data)
    print(
        f"Native gettext: {len(messages)} messages; Chinese coverage, plurals, placeholders and MO verified"
    )


if __name__ == "__main__":
    main()
